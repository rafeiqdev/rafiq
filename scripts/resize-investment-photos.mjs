#!/usr/bin/env node
/**
 * Builds narrow variants of the investment project photos.
 *
 * The photo packs arrive from the developers' sales offices at print size —
 * 1920px is typical, 3000px happens — and every surface that shows them is
 * small: the mobile page renders them 287x150 CSS px. Shipping the original
 * to a phone costs ~2MB for a strip of six thumbnails, so this writes a 400w
 * and an 800w WebP next to each source and records what exists in
 * `src/data/investmentPhotoVariants.ts`.
 *
 * The manifest is what makes this safe to re-run and safe to forget: a photo
 * added later without running this script simply isn't in the manifest, and
 * <InvestmentPhoto> serves it the way it always did instead of pointing a
 * srcset at a file that was never generated.
 *
 *   node scripts/resize-investment-photos.mjs
 *
 * Idempotent — a variant already newer than its source is left alone.
 */
import { readdir, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PHOTO_DIR = path.join(ROOT, 'public', 'img', 'investments');
const MANIFEST = path.join(ROOT, 'src', 'data', 'investmentPhotoVariants.ts');

/** Rendered widths we actually need: ~290 CSS px at 1x and at 2x/3x. */
const WIDTHS = [400, 800];
const SOURCE_RE = /\.(webp|jpe?g|png)$/i;
/** A file this script already produced — never treat one as a source. */
const VARIANT_RE = /-(\d+)w\.webp$/i;

async function newerThan(candidate, source) {
  if (!existsSync(candidate)) return false;
  const [a, b] = await Promise.all([stat(candidate), stat(source)]);
  return a.mtimeMs >= b.mtimeMs;
}

async function main() {
  const slugs = (await readdir(PHOTO_DIR, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  /**
   * slug → file → { w: intrinsic width of the source, v: variant widths made }.
   * The source width is recorded so the srcset can describe the original
   * honestly instead of guessing a `w` descriptor for it.
   */
  const manifest = {};
  let written = 0;
  let skipped = 0;
  let savedBytes = 0;

  for (const slug of slugs) {
    const dir = path.join(PHOTO_DIR, slug);
    const files = (await readdir(dir)).filter((f) => SOURCE_RE.test(f) && !VARIANT_RE.test(f)).sort();

    for (const file of files) {
      const source = path.join(dir, file);
      const meta = await sharp(source).metadata();
      const base = file.replace(SOURCE_RE, '');
      const made = [];

      for (const w of WIDTHS) {
        // Never upscale: a 412px-wide source has no honest 800w variant.
        if (meta.width && meta.width <= w) continue;
        const out = path.join(dir, `${base}-${w}w.webp`);
        if (await newerThan(out, source)) {
          made.push(w);
          skipped += 1;
          continue;
        }
        await sharp(source).resize({ width: w, withoutEnlargement: true }).webp({ quality: 78 }).toFile(out);
        made.push(w);
        written += 1;
        savedBytes += (await stat(source)).size - (await stat(out)).size;
      }

      if (made.length && meta.width) {
        manifest[slug] ??= {};
        manifest[slug][file] = { w: meta.width, v: made };
      }
    }
  }

  const body = `/**
 * Generated by scripts/resize-investment-photos.mjs — do not edit by hand.
 *
 * Maps each investment photo to the narrow variants that exist on disk beside
 * it, so <InvestmentPhoto> only ever builds a srcset out of files that were
 * really generated. A photo missing from this map is served at full size.
 *
 * \`w\` is the intrinsic width of the untouched source; \`v\` are the variant
 * widths written next to it as \`<name>-<width>w.webp\`.
 */
export interface InvestmentPhotoVariants {
  /** Intrinsic width of the original file. */
  w: number;
  /** Generated variant widths, ascending. */
  v: number[];
}

export const INVESTMENT_PHOTO_VARIANTS: Record<string, Record<string, InvestmentPhotoVariants>> = ${JSON.stringify(
    manifest,
    null,
    2,
  )};
`;
  await writeFile(MANIFEST, body, 'utf8');

  console.log(
    `investment photos: ${written} variant(s) written, ${skipped} already current, ` +
      `${(savedBytes / 1024 / 1024).toFixed(1)}MB lighter than their sources`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
